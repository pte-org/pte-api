-- Student chat (plan 261028-ninh-practice-ai-chat-box, phase 1).
-- student_id is the student's public UUID (users.public_id), the same value CurrentUser.userId() carries.

-- Daily message counter. The UNIQUE key is what makes INSERT ... ON CONFLICT (student_id, usage_date)
-- atomic: two requests in the first instant of a day can never create two counter rows.
CREATE TABLE chat_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id UUID NOT NULL,
    usage_date DATE NOT NULL,
    used INTEGER NOT NULL DEFAULT 0 CHECK (used >= 0),
    CONSTRAINT uq_chat_usage_student_date UNIQUE (student_id, usage_date)
);

-- The primary key pins a client-proposed session id to the first student that used it.
CREATE TABLE chat_session (
    session_id UUID PRIMARY KEY,
    student_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_chat_session_student ON chat_session (student_id);

-- status: OK = valid answer, REFUSED = off-topic (quota refunded), FAILED = provider error after the charge
-- (quota refunded, answer empty, finish_reason and token counts kept). on_topic is NULL when no verdict exists.
CREATE TABLE chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    session_id UUID NOT NULL,
    student_id UUID NOT NULL,
    tenant_id UUID NOT NULL,
    question VARCHAR(4000) NOT NULL,
    answer VARCHAR(20000) NOT NULL DEFAULT '',
    task_type VARCHAR(64),
    language VARCHAR(16),
    tokens_in INTEGER,
    tokens_out INTEGER,
    tokens_thinking INTEGER,
    finish_reason VARCHAR(32),
    from_cache BOOLEAN NOT NULL DEFAULT FALSE,
    on_topic BOOLEAN,
    status VARCHAR(16) NOT NULL CHECK (status IN ('OK', 'REFUSED', 'FAILED')),
    model VARCHAR(64),
    prompt_version VARCHAR(32)
);

CREATE INDEX idx_chat_message_session ON chat_message (student_id, session_id, status, id);
CREATE INDEX idx_chat_message_student_time ON chat_message (student_id, created_at);

-- Shared answers for repeated first questions. expires_at is optional; a new prompt version changes the key.
CREATE TABLE chat_answer_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    cache_key VARCHAR(64) NOT NULL UNIQUE,
    answer VARCHAR(20000) NOT NULL,
    prompt_version VARCHAR(32) NOT NULL,
    model VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE
);
