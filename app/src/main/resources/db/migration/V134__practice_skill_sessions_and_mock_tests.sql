-- Practice by skill (Study-Pack) and fixed full mock tests (plan 261025-hung-practice-study-pack-mock-tests).
-- A mock test is built once from the active Score Template and the PRACTICE question pool; its questions are
-- pinned in practice_mock_test_items so every student sees the same test and it never changes with the bank.

CREATE TABLE IF NOT EXISTS practice_mock_tests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    sequence_no INTEGER NOT NULL,
    title VARCHAR(128) NOT NULL,
    seed BIGINT NOT NULL,
    template_public_id UUID,
    template_version INTEGER,
    status VARCHAR(16) NOT NULL,
    item_count INTEGER NOT NULL,
    estimated_minutes INTEGER NOT NULL,
    version BIGINT,
    CONSTRAINT uk_practice_mock_tests_sequence UNIQUE (sequence_no),
    CONSTRAINT ck_practice_mock_tests_status CHECK (status IN ('PUBLISHED', 'HIDDEN'))
);

CREATE TABLE IF NOT EXISTS practice_mock_test_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mock_test_id BIGINT NOT NULL REFERENCES practice_mock_tests (id),
    question_public_id UUID NOT NULL,
    task_code VARCHAR(64) NOT NULL,
    section VARCHAR(32) NOT NULL,
    order_index INTEGER NOT NULL,
    CONSTRAINT uk_practice_mock_test_items_order UNIQUE (mock_test_id, order_index)
);

-- kind is null for sessions created before this migration; they are single-task practice sessions.
ALTER TABLE practice_sessions ADD COLUMN IF NOT EXISTS kind VARCHAR(16);
ALTER TABLE practice_sessions ADD COLUMN IF NOT EXISTS skill_code VARCHAR(16);
ALTER TABLE practice_sessions ADD COLUMN IF NOT EXISTS mock_test_id BIGINT REFERENCES practice_mock_tests (id);

ALTER TABLE practice_sessions ADD CONSTRAINT ck_practice_sessions_kind
    CHECK (kind IS NULL OR kind IN ('TASK', 'SKILL', 'MOCK_TEST'));

-- A full mock test has 65 questions; the 1..50 limit of V133 is the per-task-type choice of the other kinds.
ALTER TABLE practice_sessions DROP CONSTRAINT IF EXISTS ck_practice_sessions_question_count;
ALTER TABLE practice_sessions ADD CONSTRAINT ck_practice_sessions_question_count
    CHECK (question_count IS NULL OR question_count >= 1
           AND (question_count <= 50 OR kind = 'MOCK_TEST'));

CREATE INDEX IF NOT EXISTS idx_practice_sessions_student_mock_test
    ON practice_sessions (student_public_id, mock_test_id, status);

-- One unfinished attempt per student and mock test; a second tab or request resumes it instead of creating another.
CREATE UNIQUE INDEX IF NOT EXISTS uk_practice_sessions_active_mock_test
    ON practice_sessions (student_public_id, mock_test_id)
    WHERE mock_test_id IS NOT NULL AND deleted = FALSE AND status IN ('OVERVIEW', 'IN_PROGRESS');

