-- session module & identity view: attendance state, command log and staff student search view.

CREATE OR REPLACE VIEW identity_staff_student_search_view AS
SELECT
    u.tenant_id AS tenant_id,
    u.public_id AS student_public_id,
    COALESCE(NULLIF(TRIM(u.full_name), ''), u.username, u.email) AS display_name,
    u.email AS email
FROM users u
WHERE u.deleted = FALSE;

CREATE TABLE IF NOT EXISTS session_attendances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    session_id BIGINT NOT NULL REFERENCES exam_sessions (id),
    student_public_id UUID NOT NULL,
    enrollment_public_id UUID NOT NULL,
    status VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    last_actor_public_id UUID NOT NULL,
    last_actor_role VARCHAR(32) NOT NULL,
    last_action_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_reason_or_note VARCHAR(1000),
    UNIQUE (session_id, student_public_id)
);

CREATE INDEX IF NOT EXISTS idx_session_attendances_session ON session_attendances (session_id);
CREATE INDEX IF NOT EXISTS idx_session_attendances_tenant ON session_attendances (tenant_id);

CREATE TABLE IF NOT EXISTS session_attendance_commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    session_id BIGINT NOT NULL REFERENCES exam_sessions (id),
    actor_public_id UUID NOT NULL,
    actor_role VARCHAR(32) NOT NULL,
    request_public_id UUID NOT NULL,
    intent_fingerprint VARCHAR(255) NOT NULL,
    student_public_id UUID NOT NULL,
    enrollment_public_id UUID NOT NULL,
    expected_version BIGINT NOT NULL,
    applied_version BIGINT NOT NULL,
    previous_status VARCHAR(32) NOT NULL,
    new_status VARCHAR(32) NOT NULL,
    reason_or_note VARCHAR(1000),
    server_action_at TIMESTAMP WITH TIME ZONE NOT NULL,
    changed BOOLEAN NOT NULL,
    committed_result VARCHAR(32) NOT NULL,
    CONSTRAINT uk_session_attendance_cmd_receipt UNIQUE (tenant_id, session_id, actor_public_id, request_public_id)
);

CREATE INDEX IF NOT EXISTS idx_session_att_cmd_history ON session_attendance_commands (session_id, student_public_id, created_at);
CREATE INDEX IF NOT EXISTS idx_session_att_cmd_tenant ON session_attendance_commands (tenant_id);
