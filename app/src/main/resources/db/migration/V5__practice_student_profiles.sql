-- Practice student profiles (plan 261025-hung-practice-exam-date).
-- Stores student-specific practice preferences and learning targets such as exam date.

CREATE TABLE IF NOT EXISTS practice_student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    student_public_id UUID NOT NULL UNIQUE,
    tenant_id UUID NOT NULL,
    exam_date DATE,
    version BIGINT
);

CREATE INDEX IF NOT EXISTS idx_practice_student_profiles_student
    ON practice_student_profiles (student_public_id) WHERE deleted = FALSE;
