-- One-time links for self-service password reset. Only the SHA-256 of the token is stored.
CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    deleted boolean NOT NULL,
    public_id uuid NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    token_hash character varying(255) NOT NULL,
    used_at timestamp(6) with time zone,
    user_id bigint NOT NULL REFERENCES users (id),
    CONSTRAINT uk_password_reset_tokens_public_id UNIQUE (public_id),
    CONSTRAINT uk_password_reset_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_password_reset_user ON password_reset_tokens USING btree (user_id);

-- The notification log keeps an allowlist of types; the reset mail is a new one.
ALTER TABLE notification_logs
    DROP CONSTRAINT IF EXISTS notification_logs_notification_type_check;

ALTER TABLE notification_logs
    ADD CONSTRAINT notification_logs_notification_type_check
        CHECK (notification_type IN (
            'STUDENT_ENROLLED',
            'ATTEMPT_PUBLISHED',
            'VIOLATION_DETECTED',
            'SESSION_CANCELLED',
            'STUDENT_ENROLLMENT_CONFLICT',
            'TENANT_APPLICATION_SUBMITTED',
            'TENANT_APPLICATION_APPROVED',
            'TENANT_APPLICATION_REJECTED',
            'USER_CREDENTIALS_SENT',
            'PRACTICE_EMAIL_CHALLENGE',
            'PASSWORD_RESET_LINK_SENT'
        ));
