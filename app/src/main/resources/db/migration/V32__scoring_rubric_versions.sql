-- Scoring rubric versions (plan quang-scoring-rubric-transparency, phase 2). Additive: runs on a database already at
-- V31 and on an empty one.
--
-- scoring_rubric_versions.parameters always holds the FULL numeric parameters of all 22 task types; it never means
-- "use the code defaults". Shape (shared with RubricParametersCodec / RubricParametersValidator):
--   {"azureBandMappingVersion": 1,
--    "taskTypes": {"<TASK_TYPE>": {"traitWeights": {"<TRAIT>": 0..10},
--                                  "traitScales": {"<TRAIT>": max >= 1 | "PER_WORD"},
--                                  "formBands": null | [{"minWords": n, "maxWords": n, "band": n}],
--                                  "gateEnabled": {"<GATE_TRAIT>": true|false}}}}

CREATE TABLE scoring_rubric_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    lock_version BIGINT NOT NULL DEFAULT 0,
    version_no INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL,
    parameters JSONB NOT NULL,
    catalog_version INTEGER NOT NULL,
    author_user_public_id UUID,
    approver_user_public_id UUID,
    rejection_reason VARCHAR(1000),
    submitted_at TIMESTAMP(6) WITH TIME ZONE,
    decided_at TIMESTAMP(6) WITH TIME ZONE,
    activated_at TIMESTAMP(6) WITH TIME ZONE,
    retired_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uq_scoring_rubric_versions_public_id UNIQUE (public_id),
    CONSTRAINT uq_scoring_rubric_versions_version_no UNIQUE (version_no),
    CONSTRAINT scoring_rubric_versions_status_check
        CHECK (status IN ('DRAFT', 'PENDING', 'ACTIVE', 'REJECTED', 'RETIRED')),
    CONSTRAINT scoring_rubric_versions_version_no_check CHECK (version_no >= 1),
    CONSTRAINT scoring_rubric_versions_catalog_version_check CHECK (catalog_version >= 1),
    CONSTRAINT scoring_rubric_versions_parameters_object_check CHECK (jsonb_typeof(parameters) = 'object')
);

-- At most one ACTIVE version (same pattern as ux_exam_definitions_single_active).
CREATE UNIQUE INDEX ux_scoring_rubric_versions_single_active
    ON scoring_rubric_versions (status) WHERE status = 'ACTIVE';

