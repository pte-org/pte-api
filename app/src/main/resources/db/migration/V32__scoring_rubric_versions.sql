-- Immutability of ACTIVE and RETIRED rows. The only UPDATE allowed on such a row is ACTIVE -> RETIRED, changing
-- nothing but status, retired_at, updated_at and lock_version. Every other column (parameters, catalog_version,
-- version_no, author/approver, activated_at, deleted, ...) is compared as a whole row, so a column added later is
-- protected too and NULL columns cannot slip through a "<>" comparison. Rows in DRAFT/PENDING/REJECTED stay editable
-- and may become ACTIVE (setting activated_at and approver_user_public_id); only an ACTIVE row may become RETIRED.
CREATE FUNCTION scoring_rubric_versions_guard_update() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status IN ('ACTIVE', 'RETIRED') THEN
        IF OLD.status = 'ACTIVE' AND NEW.status = 'RETIRED'
           AND (to_jsonb(NEW) - 'status' - 'retired_at' - 'updated_at' - 'lock_version')
               = (to_jsonb(OLD) - 'status' - 'retired_at' - 'updated_at' - 'lock_version') THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'scoring_rubric_versions %: % row is immutable (only ACTIVE -> RETIRED is allowed)',
            OLD.public_id, OLD.status USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.status = 'RETIRED' THEN
        RAISE EXCEPTION 'scoring_rubric_versions %: only an ACTIVE version can be retired', OLD.public_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_scoring_rubric_versions_guard_update
    BEFORE UPDATE ON scoring_rubric_versions
    FOR EACH ROW EXECUTE FUNCTION scoring_rubric_versions_guard_update();

CREATE FUNCTION scoring_rubric_versions_guard_delete() RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status IN ('ACTIVE', 'RETIRED') THEN
        RAISE EXCEPTION 'scoring_rubric_versions %: % row cannot be deleted', OLD.public_id, OLD.status
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_scoring_rubric_versions_guard_delete
    BEFORE DELETE ON scoring_rubric_versions
    FOR EACH ROW EXECUTE FUNCTION scoring_rubric_versions_guard_delete();

-- Activation audits are INSERT-only.
CREATE FUNCTION scoring_rubric_activation_audits_insert_only() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'scoring_rubric_activation_audits is insert-only (% rejected)', TG_OP
        USING ERRCODE = 'check_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_scoring_rubric_activation_audits_no_update_delete
    BEFORE UPDATE OR DELETE ON scoring_rubric_activation_audits
    FOR EACH ROW EXECUTE FUNCTION scoring_rubric_activation_audits_insert_only();

CREATE TRIGGER trg_scoring_rubric_activation_audits_no_truncate
    BEFORE TRUNCATE ON scoring_rubric_activation_audits
    FOR EACH STATEMENT EXECUTE FUNCTION scoring_rubric_activation_audits_insert_only();

