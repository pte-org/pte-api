-- V99: Proctor identity verification and exam session incidents

ALTER TABLE session_attendances
    ADD COLUMN IF NOT EXISTS identity_status VARCHAR(32) NOT NULL DEFAULT 'UNVERIFIED',
    ADD COLUMN IF NOT EXISTS identity_note VARCHAR(1000);

CREATE TABLE IF NOT EXISTS session_identity_verification_commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    session_id BIGINT NOT NULL REFERENCES exam_sessions (id),
    actor_public_id UUID NOT NULL,
    actor_role VARCHAR(32) NOT NULL,
    request_public_id UUID NOT NULL,
    intent_fingerprint VARCHAR(255) NOT NULL,
    student_public_id UUID NOT NULL,
    enrollment_public_id UUID NOT NULL,
    expected_version BIGINT NOT NULL,
    applied_version BIGINT NOT NULL,
    previous_status VARCHAR(32) NOT NULL,
    new_status VARCHAR(32) NOT NULL,
    note VARCHAR(1000),
    server_action_at TIMESTAMP WITH TIME ZONE NOT NULL,
    changed BOOLEAN NOT NULL,
    committed_result VARCHAR(32) NOT NULL,
    CONSTRAINT uk_session_identity_cmd_receipt UNIQUE (tenant_id, session_id, actor_public_id, request_public_id)
);

CREATE INDEX IF NOT EXISTS idx_session_id_cmd_history ON session_identity_verification_commands (session_id, student_public_id, created_at);
CREATE INDEX IF NOT EXISTS idx_session_id_cmd_tenant ON session_identity_verification_commands (tenant_id);

CREATE TABLE IF NOT EXISTS exam_session_incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    session_public_id UUID NOT NULL,
    student_public_id UUID,
    attempt_public_id UUID,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(64) NOT NULL,
    severity VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'NEW',
    reporter_role VARCHAR(32) NOT NULL,
    reporter_name VARCHAR(255) NOT NULL,
    reporter_public_id UUID NOT NULL,
    current_owner_role VARCHAR(32) NOT NULL,
    current_owner_name VARCHAR(255),
    resolution_summary TEXT
);

CREATE INDEX IF NOT EXISTS idx_exam_session_incidents_session
    ON exam_session_incidents (session_public_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_exam_session_incidents_tenant
    ON exam_session_incidents (tenant_id);

CREATE TABLE IF NOT EXISTS exam_session_incident_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    incident_id BIGINT NOT NULL REFERENCES exam_session_incidents (id),
    incident_public_id UUID NOT NULL,
    actor_public_id UUID NOT NULL,
    actor_name VARCHAR(255) NOT NULL,
    actor_role VARCHAR(32) NOT NULL,
    action VARCHAR(64) NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    notes TEXT
);

CREATE INDEX IF NOT EXISTS idx_exam_session_inc_hist_incident
    ON exam_session_incident_history (incident_id, created_at ASC);
