-- Examiner workflow, durable drafts, idempotent commands, audit events, and assignment issues.

CREATE TABLE IF NOT EXISTS examiner_grading_work (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    session_public_id UUID NOT NULL,
    attempt_public_id UUID NOT NULL,
    assignment_public_id UUID NOT NULL REFERENCES examiner_attempt_assignments (public_id),
    examiner_public_id UUID NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    version BIGINT NOT NULL DEFAULT 1,
    started_at TIMESTAMP WITH TIME ZONE,
    finalized_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_examiner_grading_work_assignment UNIQUE (tenant_id, assignment_public_id)
);

CREATE INDEX IF NOT EXISTS idx_examiner_grading_work_owner
    ON examiner_grading_work (tenant_id, examiner_public_id, status);
CREATE INDEX IF NOT EXISTS idx_examiner_grading_work_target
    ON examiner_grading_work (tenant_id, session_public_id, attempt_public_id);

CREATE TABLE IF NOT EXISTS examiner_answer_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    work_id BIGINT NOT NULL REFERENCES examiner_grading_work (id),
    answer_public_id UUID NOT NULL,
    score INTEGER,
    comment VARCHAR(2000),
    decision_kind VARCHAR(32),
    expected_review_version VARCHAR(128),
    reviewed_ai_version VARCHAR(128),
    version BIGINT NOT NULL DEFAULT 1,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_examiner_draft_work_answer UNIQUE (work_id, answer_public_id),
    CONSTRAINT ck_examiner_draft_score CHECK (score IS NULL OR (score BETWEEN 0 AND 100))
);

CREATE INDEX IF NOT EXISTS idx_examiner_draft_tenant_answer
    ON examiner_answer_drafts (tenant_id, answer_public_id);

CREATE TABLE IF NOT EXISTS examiner_grading_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    tenant_id UUID NOT NULL,
    work_id BIGINT NOT NULL REFERENCES examiner_grading_work (id),
    answer_public_id UUID,
    operation VARCHAR(32) NOT NULL,
    work_version BIGINT NOT NULL,
    draft_version BIGINT,
    metadata JSONB,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_examiner_grading_events_work
    ON examiner_grading_events (tenant_id, work_id, occurred_at);

CREATE TABLE IF NOT EXISTS examiner_grading_commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    tenant_id UUID NOT NULL,
    examiner_public_id UUID NOT NULL,
    assignment_public_id UUID NOT NULL,
    request_public_id UUID NOT NULL,
    operation VARCHAR(32) NOT NULL,
    fingerprint VARCHAR(128) NOT NULL,
    receipt_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_examiner_cmd_receipt UNIQUE (tenant_id, examiner_public_id, assignment_public_id, request_public_id)
);

CREATE INDEX IF NOT EXISTS idx_examiner_cmd_assignment
    ON examiner_grading_commands (tenant_id, assignment_public_id, request_public_id);

CREATE TABLE IF NOT EXISTS examiner_grading_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id UUID NOT NULL,
    work_id BIGINT NOT NULL REFERENCES examiner_grading_work (id),
    answer_public_id UUID,
    type VARCHAR(32) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    reported_by UUID NOT NULL,
    reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_by UUID,
    resolved_at TIMESTAMP WITH TIME ZONE,
    resolution VARCHAR(2000)
);

CREATE INDEX IF NOT EXISTS idx_examiner_grading_issues_work
    ON examiner_grading_issues (tenant_id, work_id, status);
