-- AI dispatch token: a worker result counts only while the row still awaits the latest dispatch.
-- ai_dispatched_at lets a host re-dispatch a job that never came back; rows already AI_SCORING stay NULL
-- and are treated as stale on the next host scoring request.

ALTER TABLE scoring_answers
    ADD COLUMN dispatch_token BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN ai_dispatched_at TIMESTAMP WITH TIME ZONE;

-- The detail behind an AI score (criteria, feedback, transcript) or why it failed. One row per answer.
CREATE TABLE scoring_answer_ai_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    answer_public_id UUID NOT NULL,
    tenant_id UUID NOT NULL,
    criteria_scores_json TEXT,
    feedback TEXT,
    transcript TEXT,
    detail_json TEXT,
    fallback BOOLEAN NOT NULL DEFAULT FALSE,
    failure_reason VARCHAR(40),
    CONSTRAINT uq_scoring_answer_ai_detail_answer UNIQUE (answer_public_id)
);
