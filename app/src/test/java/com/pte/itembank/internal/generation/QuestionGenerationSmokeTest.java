/**
 * Smoke test for the real AI generation pipeline. Skipped by default unless QUESTION_GEN_SMOKE is set.
 * When run, tests each of the 8 text-generation task types with a real LLM (9router).
 * Prints only the generated question IDs to stdout.
 */
@SpringBootTest
@ActiveProfiles("test")
@EnabledIfEnvironmentVariable(named = "QUESTION_GEN_SMOKE", matches = ".+")
@Transactional
class QuestionGenerationSmokeTest {

    @Autowired
    private QuestionGenerationJobService jobService;

    @Autowired
    private QuestionRepository questionRepository;

    private static final String[] SUPPORTED_TEXT_TYPES = {
        "MC_READING_SINGLE",
        "MC_READING_MULTIPLE",
        "FILL_IN_THE_BLANKS_DROPDOWN",
        "FILL_IN_THE_BLANKS_DRAG_AND_DROP",
        "RE_ORDER_PARAGRAPHS",
        "SUMMARIZE_WRITTEN_TEXT",
        "WRITE_ESSAY",
        "READ_ALOUD"
    };

    private static final CurrentUser PLATFORM_ADMIN = new CurrentUser(
        UUID.fromString("00000000-0000-0000-0000-000000000001"),
        null,
        List.of(SecurityRoles.PLATFORM_ADMIN)
    );

    @Test
    void testGenerateAllTextTaskTypes() {
        List<UUID> generatedIds = new ArrayList<>();

        for (String taskType : SUPPORTED_TEXT_TYPES) {
            UUID jobId = submitGenerationJob(taskType);
            waitForJobCompletion(jobId);
            List<UUID> questionIds = findGeneratedQuestions(jobId);
            generatedIds.addAll(questionIds);
            System.out.println(taskType + ": " + questionIds);
        }

        System.out.println("\nGenerated question IDs:");
        generatedIds.forEach(System.out::println);
    }

    private UUID submitGenerationJob(String taskType) {
        SubmitGenerationJobRequest request = new SubmitGenerationJobRequest(
                taskType,
                "B2",
                QuestionPool.EXAM.name(),
                "technology",
                1
        );
        var response = jobService.submit(request, PLATFORM_ADMIN);
        return response.publicId();
    }

    private void waitForJobCompletion(UUID jobId) {
        // Simplified: poll until items are completed
        // In a real scenario, this would check the job status periodically
        // For now, just sleep to allow the worker to run
        try {
            Thread.sleep(5000);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }

    private List<UUID> findGeneratedQuestions(UUID jobId) {
        // Find questions generated by this job
        return questionRepository.findAll().stream()
                .filter(q -> jobId.equals(q.getGenerationJobPublicId()))
                .map(Question::getPublicId)
                .toList();
    }
}
